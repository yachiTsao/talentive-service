/**
 * 合約：GET /health
 *
 * 用途：健康檢查端點，供前端、CI 與 Docker HEALTHCHECK 使用。
 * 永遠回傳 HTTP 200，狀態碼本身即代表服務存活。
 */

// ─────────────────────────────────────────────
// 請求（無 body、無 query params、無 headers 要求）
// ─────────────────────────────────────────────

// GET /health
// HTTP/1.1

// ─────────────────────────────────────────────
// 回應
// ─────────────────────────────────────────────

/**
 * HTTP 200 OK
 * Content-Type: application/json; charset=utf-8
 */
export interface HealthResponse {
  /** 永遠為 true（200 OK 代表服務存活） */
  ok: true;
  /** 目前是否有爬蟲任務正在執行 */
  running: boolean;
  /** 最後一次爬取的摘要；尚無任何爬取時為 null */
  last: { at: string; count: number } | null;
}

// ─────────────────────────────────────────────
// 錯誤情境
// ─────────────────────────────────────────────
// 本端點不回傳 4xx / 5xx：
//   - 若服務崩潰，TCP 連線本身即會失敗（由呼叫方視為不健康）。
//   - 本端點不需驗證 token 或 body。

// ─────────────────────────────────────────────
// 範例
// ─────────────────────────────────────────────

/*
  回應範例 A（閒置中）
  {
    "ok": true,
    "running": false,
    "last": null
  }

  回應範例 B（爬蟲執行中，上次爬取有 42 筆）
  {
    "ok": true,
    "running": true,
    "last": { "at": "2025-04-05T10:30:00.000Z", "count": 42 }
  }
*/
